import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const execFileAsync = promisify(execFile);
const projectDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const configPath = path.join(projectDirectory, 'scripts', 'uikit-docs.json');
const shouldCheck = process.argv.includes('--check');

const config = JSON.parse(await readFile(configPath, 'utf8'));
const sourceRoot = path.resolve(projectDirectory, config.sourceRoot);

async function revision() {
    try {
        const result = await execFileAsync('git', ['-C', sourceRoot, 'rev-parse', 'HEAD']);
        return result.stdout.trim();
    } catch {
        return 'unknown revision';
    }
}

function replaceGlossClasses(source) {
    return source.replaceAll('uk-', 'gls-');
}

function convertExampleFences(source) {
    const lines = source.split(/\r?\n/);
    const output = [];

    for (let index = 0; index < lines.length; index += 1) {
        if (lines[index].trim() !== '```example') {
            output.push(lines[index]);
            continue;
        }

        const example = [];
        index += 1;

        while (index < lines.length && lines[index].trim() !== '```') {
            example.push(lines[index]);
            index += 1;
        }

        output.push(
            '<div class="gls-docs-example">',
            ...example,
            '</div>',
            '',
            '```html',
            ...example,
            '```',
        );
    }

    return output.join('\n');
}

function rewriteDocumentationLinks(source) {
    return source.replace(/\]\(([^)\s]+\.md)(#[^)]*)?\)/g, (_match, file, hash = '') => {
        const slug = path.posix.basename(file, '.md');
        return `](https://getuikit.com/docs/${slug}${hash})`;
    });
}

function addFrontMatter(source, title, sourcePath, sourceRevision) {
    return [
        '---',
        `title: ${title}`,
        '---',
        '',
        `<!-- Generated from ${sourcePath} at ${sourceRevision}. Do not edit this file by hand. -->`,
        '',
        source.trim(),
        '',
    ].join('\n');
}

function titleFromSource(sourcePath) {
    return path.posix
        .basename(sourcePath, path.posix.extname(sourcePath))
        .replaceAll('-', ' ')
        .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

async function renderPage(page, sourceRevision) {
    const sourcePath = path.resolve(sourceRoot, page.source);
    const destinationPath = path.resolve(projectDirectory, page.destination);
    const source = await readFile(sourcePath, 'utf8');
    const transformed = rewriteDocumentationLinks(
        convertExampleFences(replaceGlossClasses(source)),
    );
    const rendered = addFrontMatter(
        transformed,
        page.title ?? titleFromSource(page.source),
        page.source,
        sourceRevision,
    );

    if (shouldCheck) {
        let current;

        try {
            current = await readFile(destinationPath, 'utf8');
        } catch (error) {
            if (error.code === 'ENOENT') {
                throw new Error(`${page.destination} is missing. Run npm run sync:uikit-docs.`, {
                    cause: error,
                });
            }

            throw error;
        }

        if (current !== rendered) {
            throw new Error(`${page.destination} is stale. Run npm run sync:uikit-docs.`);
        }

        return;
    }

    await mkdir(path.dirname(destinationPath), { recursive: true });
    await writeFile(destinationPath, rendered);
}

const sourceRevision = await revision();

for (const page of config.pages) {
    await renderPage(page, sourceRevision);
}

if (shouldCheck) {
    console.log(`UIkit documentation is up to date at ${sourceRevision}.`);
} else {
    console.log(`Synced ${config.pages.length} UIkit documentation page(s) at ${sourceRevision}.`);
}
